"""A deterministic synthetic-data exercise. Standard library only; no model/network.

Run from any directory: python path/to/contest-starter-example/run.py
"""
from __future__ import annotations

import csv
import hashlib
import html
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "data/raw/tickets.csv"
OUTPUT = ROOT / "results"
LABELS = {"library": "图书馆", "dorm": "宿舍", "classroom": "教学楼"}


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def read_records():
    with SOURCE.open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    seen = set()
    valid, rejected = [], []
    for index, raw in enumerate(rows, 2):
        ticket = raw["ticket_id"].strip()
        category = raw["category"].strip()
        value = raw["response_minutes"].strip()
        reason = None
        if not ticket:
            reason = "missing_id"
        elif ticket in seen:
            reason = "duplicate_id"
        elif not category:
            reason = "missing_category"
        elif not value:
            reason = "missing_minutes"
        else:
            try:
                minutes = float(value)
            except ValueError:
                reason = "nonnumeric_minutes"
            else:
                if not math.isfinite(minutes):
                    reason = "nonfinite_minutes"
                elif minutes < 0:
                    reason = "negative_minutes"
        if ticket:
            seen.add(ticket)
        if reason:
            rejected.append({"source_line": index, **raw, "reason": reason})
        else:
            valid.append({"ticket_id": ticket, "category": category, "minutes": minutes})
    return rows, valid, rejected


def make_chart(groups) -> str:
    svg = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="860" height="440" viewBox="0 0 860 440">',
        '<rect width="860" height="440" fill="#f3f7f8"/>',
        '<g font-family="Arial,sans-serif" fill="#162c3b">',
        '<text x="44" y="48" font-size="17" fill="#007e87">SYNTHETIC PRACTICE DATA - NOT A REAL SURVEY</text>',
        '<text x="44" y="92" font-size="28" font-weight="bold">Mean response time by category</text>',
    ]
    largest = max(group["mean_minutes"] for group in groups)
    for index, group in enumerate(groups):
        y = 145 + index * 72
        width = group["mean_minutes"] / largest * 475
        svg.append(f'<text x="44" y="{y+27}" font-size="20">{html.escape(group["category"])}</text>')
        svg.append(f'<rect x="170" y="{y}" width="{width:.2f}" height="40" rx="5" fill="#007e87"/>')
        svg.append(f'<text x="{185+width:.2f}" y="{y+27}" font-size="19">{group["mean_minutes"]:g} min</text>')
    svg.extend([
        '<text x="44" y="395" font-size="16">10 valid synthetic records; averages describe this fixture only.</text>',
        '<text x="44" y="420" font-size="14" fill="#526673">Source: data/raw/tickets.csv | Generated by run.py</text>',
        '</g></svg>',
    ])
    return "\n".join(svg) + "\n"


def main() -> None:
    OUTPUT.mkdir(exist_ok=True)
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    rows, valid, rejected = read_records()
    groups = []
    for category in sorted({row["category"] for row in valid}):
        values = [row["minutes"] for row in valid if row["category"] == category]
        groups.append({"category": category, "label": LABELS.get(category, category),
                       "count": len(values), "total_minutes": sum(values),
                       "mean_minutes": sum(values) / len(values)})
    summary = {"purpose": "synthetic_practice_not_real_survey", "input_rows": len(rows),
               "valid_rows": len(valid), "rejected_rows": len(rejected),
               "total_minutes": sum(row["minutes"] for row in valid), "groups": groups,
               "source": "data/raw/tickets.csv", "source_sha256": source_hash,
               "model_calls": 0}
    write_json(OUTPUT / "summary.json", summary)
    with (OUTPUT / "summary.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["category", "label", "count", "total_minutes", "mean_minutes"])
        writer.writeheader()
        writer.writerows(groups)
    with (OUTPUT / "rejected.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["source_line", "ticket_id", "category", "response_minutes", "reason"])
        writer.writeheader()
        writer.writerows(rejected)
    (OUTPUT / "chart.svg").write_text(make_chart(groups), encoding="utf-8")
    checks = {
        "row_accounting": len(rows) == len(valid) + len(rejected) == 15,
        "expected_valid_and_rejected": len(valid) == 10 and len(rejected) == 5,
        "unique_valid_ids": len({r["ticket_id"] for r in valid}) == len(valid),
        "known_fixture_total": summary["total_minutes"] == 450,
        "known_fixture_means": {g["category"]: g["mean_minutes"] for g in groups} == {"classroom": 40, "dorm": 60, "library": 30},
        "source_unchanged": hashlib.sha256(SOURCE.read_bytes()).hexdigest() == source_hash,
        "chart_marks_synthetic": "SYNTHETIC PRACTICE DATA" in (OUTPUT / "chart.svg").read_text(encoding="utf-8"),
    }
    write_json(OUTPUT / "checks.json", {"purpose": "fixed_fixture_acceptance", "passed": all(checks.values()), "checks": checks})
    lines = ["# 合成工单练习结果", "", "**合成教学数据，不是真实调研或竞赛成绩。**", "",
             f"输入{len(rows)}条，有效{len(valid)}条，剔除{len(rejected)}条；有效响应时长合计{summary['total_minutes']:g}分钟。", "",
             "| 类别 | 记录数 | 总分钟 | 平均分钟 |", "| --- | ---: | ---: | ---: |"]
    lines.extend(f"| {g['label']} | {g['count']} | {g['total_minutes']:g} | {g['mean_minutes']:g} |" for g in groups)
    lines.extend(["", "[查看带合成标识的图](chart.svg) · [结构化结果](summary.json) · [剔除原因](rejected.csv)", "",
                  "限制：这是固定作者合成样例，无随机抽样和真实场景代表性；均值不能证明因果。", "",
                  "复跑：在练习目录执行 `python run.py`。脚本只用标准库，不联网，不调用模型，也不读取账号或密钥。", "",
                  f"原始输入SHA256：`{source_hash}`。"])
    (OUTPUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if not all(checks.values()):
        raise SystemExit("Fixture acceptance failed; inspect results/checks.json")
    print("Synthetic practice complete: 15 input, 10 valid, 5 rejected, 450 minutes.")
    print("Open results/report.md and results/chart.svg. Acceptance: 7/7 passed; model calls: 0.")


if __name__ == "__main__":
    main()
