"""Generate reader-facing contest cards and compatibility views from one source.

Edit data/competitions.json, then run this script. --check detects stale output
without writing. Source facts, dated limits and unknowns are never guessed here.
"""
from __future__ import annotations
import argparse,json,re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DATE='2026-11-17'
GENERATED='<!-- Generated by scripts/build_catalog.py from data/competitions.json. Do not edit by hand. -->'
EXPLORER='https://github.com/Rain-dust/HowToCompeteBetter/releases/latest/download/explorer.html'

def read_data():
    rows=json.loads((ROOT/'data/competitions.json').read_text('utf8'))
    ids=[r['id'] for r in rows]
    if len(ids)!=len(set(ids)):raise ValueError('Duplicate catalog IDs')
    ranked=sorted((r for r in rows if r['rank'] is not None),key=lambda r:r['rank'])
    if [r['rank'] for r in ranked]!=list(range(1,28)):raise ValueError('Reference ranks must be 1–27')
    for r in rows:
        if not isinstance(r['playbook'],list) or not isinstance(r['detail'],dict):raise ValueError('Nonuniform record '+r['id'])
        if not r['decision_label'] or not r['cost_summary'] or not r['entry_links']:raise ValueError('Incomplete reader card '+r['id'])
        if r['card_path']!='docs/contests/'+r['id']+'.md':raise ValueError('Noncanonical card path')
        if r['rank'] is not None and r['ranking_view']['catalog_id']!=r['id']:raise ValueError('Broken rank mapping')
        if r['rank'] is not None:
            for key in ['decision_label','decision_note','cost_summary','card_path','entry_links']:
                if r['ranking_view'].get(key)!=r[key]:raise ValueError('Conflicting compatibility field '+r['id']+': '+key)
            if r['ranking_view']['rank']!=r['rank']:raise ValueError('Conflicting reference rank '+r['id'])
    return rows,ranked

def cell(s):return str(s).replace('|','\\|').replace('\n',' ')
def local(target):
    path,sep,anchor=target.partition('#')
    return '../../'+path+(sep+anchor if sep else '')
def numbered(rows):return '\n'.join(f'{i}. {s}' for i,s in enumerate(rows,1))
def linked(label,url):return f'[{label}]({url})'

def card(r):
    cs=r['cost_summary'];e=r['entry_links'];rank=r['rank']
    lines=[GENERATED,'',f"# {r['name']}",'',f"**当届建议：{r['decision_label']}**",'',r['decision_note'],'',
      '[返回首页连续榜](../../README.md) · [下载离线筛选页（浏览器打开）]('+EXPLORER+') · [全部赛事索引](../competition-catalog.md)','',
      '| 先看 | 结论 |','| --- | --- |',
      f"| 一句话 | {cell(r['summary'])} |",
      f"| 适合谁 / 资格 | {cell(r['scope'])} |",
      f"| 奖项路径 | {cell(r['award'])} |",
      f"| 实际交付 | {cell(r['deliver'])} |",
      f"| 人工不能省 | {cell('；'.join(r['human_tasks']))} |",
      f"| 证据成熟度 | {cell(r['evidence_label'])} |",
      f"| 已记录的届次状态 | {cell((r.get('ranking_view') or {}).get('current_status') or r.get('cycle') or '当前报名及下一届状态待核')} |",
      f"| 参考顺序 | {'第'+str(rank)+'名；制作适配顺序，不是当届推荐或获奖率' if rank else '补充入口；不分配主榜名次'} |",'',
      '## 要投入什么','', '| 项目 | 目前能确认的内容 |','| --- | --- |',
      f"| 人数与组队 | {cell(cs['team'])} |",f"| 时间 | {cell(cs['time'])} |",
      f"| 报名费 | {cell(cs['registration_fee'])} |",f"| 模型费用 | {cell(cs['model_fee'])} |",
      f"| 设备 / 平台 | {cell(cs['hardware'])} |",'',
      '未知不表示免费或无需设备。不同届次、赛项和学校推荐要求分别核，不把旧估算用于名次计算。','',
      '## 安装和启动','',f"**工具路线：** {r['tool_name']}。",'']
    if r['tool_tutorial'].split('#')[0]!=r['card_path']:
        lines += [linked('打开本项目的具体操作步骤',local(r['tool_tutorial'])),'']
    lines += [numbered(r['playbook']),'']
    tv=r.get('top5_view')
    if tv:
        lines+=['<details>','<summary>复制安装与启动任务</summary>','','以下任务必须结合上面的当届建议使用；限制核心直出的赛事只用于练习或获准辅助。','','安装：','','~~~text',tv['install'],'~~~','','启动：','','~~~text',tv['start'],'~~~','','</details>','']
    else:
        lines+=['<details>','<summary>复制一个最小启动任务</summary>','','~~~text',r['detail']['prompt'],'~~~','','</details>','']
    lines+=['## 官网、报名与规则','',f"- 赛事首页：{linked('打开赛事官网',e['homepage']) if e['homepage'] else '待核，未把学校转载或规则页冒充官网。'}",
      f"- 报名入口：{linked('打开报名平台',e['registration']) if e['registration'] else '待核。先看当届通知及本校推荐流程，不预设可以直接个人报名。'}",
      '- 报名状态：'+r['entry_status'],
      '- 规则核查截至：'+r['rules_checked_through']+'；页面整理更新：'+DATE+'。']
    if e['rules']:
        lines+=['- 已读规则 / 通知：']+[f"  - {linked(s['label'],s['url'])}" for s in e['rules']]
    else:lines+=['- 完整当届规则：尚待取得。']
    lines+=['','<details>','<summary>展开依据、原始限制与旧估算</summary>','',
      '**工具与参赛范围**','',r.get('rule') or (r.get('ranking_view') or {}).get('ai_scope') or r['decision_note'],'',
      '**证据能支持什么**','',r['evidence_note'],'',
      '来源编号：'+str(r.get('feedback_sources') or '暂无独立亲历材料')+'。编号对应[反馈解读](../field-feedback.md)或[知识整理台账](../../data/knowledge-import.json)，不计作获奖概率。','']
    if r.get('fact'):lines+=['**已记录事实**','',r['fact'],'']
    if r.get('text'):lines+=['**原资料补充**','',r['text'],'']
    if r.get('implementation_notes'):lines+=['**既有实现 / 工具备注**','',r['implementation_notes'],'']
    lines+=['**时间与费用旧备注**','',cs.get('legacy_estimate') or '未测量。','',cs.get('legacy_cost_note') or '', '',cs['basis'],'']
    if r.get('tool_url'):lines+=['工具原项目：'+linked(r['tool_name'],r['tool_url'])+'。工具文档不是正式参赛许可。','']
    sources={s['url']:s for s in r.get('source_refs',[])}
    for s in r.get('rule_sources',[]):sources.setdefault(s['url'],{'title':s['label'],'url':s['url'],'type':s.get('basis','规则资料'),'note':s.get('supports',''),'checked_through':s.get('checked_through','待核')})
    for s in sources.values():lines+=['- '+linked(s['title'],s['url'])+' · '+s.get('type','资料')+' · '+s.get('checked_through','待核')+'。'+s.get('note','')]
    if not sources:lines+=['- 当届官方原文仍待补齐；不以获奖自述替代规则。']
    lines+=['','</details>','', '[下一步：如何验证作品与准备答辩](../project-delivery.md) · [数据入口](../data-sources.md)','']
    return '\n'.join(lines)

def index(rows,ranked):
    others=sorted((r for r in rows if r['rank'] is None),key=lambda r:r['id'])
    lines=[GENERATED,'','# 全部赛事：点名字看完整卡片','',f'**{len(rows)}条参考入口，主榜27项。** 其中包含母赛分支、平台、境外与省级入口，不代表{len(rows)}项独立竞赛。', '',
      '[下载离线筛选页（浏览器打开）]('+EXPLORER+') · [回首页连续榜](../README.md) · [新手选赛](competition-playbook.md)','',
      '参考顺序只表示制作适配与既有反馈的编辑判断。**先看“当届建议”，再看名次。** 完整备赛工时未作可比测量，不计算获奖率。', '',
      '每张卡统一给出资格、奖项路径、实际交付、人工任务、成本未知项、工具步骤和规则依据；官网、报名、规则分开列。', '',
      '## 连续参考顺序 1–27','', '| 参考顺序 | 比赛 / 赛项 | 当届建议 | 证据成熟度 |','| :--: | --- | --- | --- |']
    for r in ranked:lines.append(f"| {r['rank']} | [{cell(r['ranking_view']['name'])}](contests/{r['id']}.md) | {cell(r['decision_label'])} | {cell(r['evidence_label'])} |")
    lines+=['','## 其余参考入口','', '以下未分配主榜名次；可用上方筛选缩小范围。不要把“未排名”当作已排除，也不要仅因能生成作品就认定获准参赛。','', '| 比赛 / 赛项 | 当届建议 | 资格 / 适用范围 |','| --- | --- | --- |']
    for r in others:lines.append(f"| [{cell(r['name'])}](contests/{r['id']}.md) | {cell(r['decision_label'])} | {cell(r['scope'])} |")
    lines+=['','## 这次补齐了什么','', '原榜第8名华中杯缺少详情映射，本版补H01卡，沿用已有证据和待核边界。数量增加是补齐漏卡，不是新取得一项参赛实测。', '',
      '页面由[data/competitions.json](../data/competitions.json)生成。来源的原核查日期分别保留，不因本页更新至'+DATE+'而声称全部规则重新核验。','']
    return '\n'.join(lines)

def top_index(ranked):
    lines=[GENERATED,'','# 参考前五：从对应赛事卡开始','',
      '**名次表示制作适配，不等于当届正式赛推荐。** 先看每项的“当届建议”；安装与启动任务只维护在同一份赛事事实源，再生成到赛事卡。','',
      '| 顺序 | 具体入口 | 当届建议 | 操作路线 |','| :--: | --- | --- | --- |']
    for r in ranked[:5]:lines.append(f"| {r['rank']} | [{r['ranking_view']['name']}](contests/{r['id']}.md) | {r['decision_label']} | [安装与启动](contests/{r['id']}.md#安装和启动) |")
    for r in ranked[:5]:
        lines += ['',f"## {r['rank']}. {r['ranking_view']['name']}",'',r['decision_note'],'',f"[打开完整赛事卡及复制任务](contests/{r['id']}.md#安装和启动)"]
    lines+=['','数模直接选[Modex官方路线](modex.md)或[Codex/Claude固定技能链](coding-agent.md)。Modex未在本项目实测，Claude未做本轮端到端运行；实际完成的是Codex历史题复现实验。', '',
      '[返回首页](../README.md) · [下载离线筛选页（浏览器打开）]('+EXPLORER+') · [全部赛事](competition-catalog.md)','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    rows,ranked=read_data();outputs={}
    for r in rows:outputs[r['card_path']]=card(r)
    outputs['docs/competition-catalog.md']=index(rows,ranked)
    outputs['docs/top5-start.md']=top_index(ranked)
    outputs['data/ranking.json']=json.dumps([r['ranking_view'] for r in ranked],ensure_ascii=False,indent=2)+'\n'
    outputs['data/top5.json']=json.dumps([r['top5_view'] for r in ranked[:5]],ensure_ascii=False,indent=2)+'\n'
    stale=[]
    for path,text in outputs.items():
        target=ROOT/path
        if a.check:
            if not target.exists() or target.read_text('utf8')!=text:stale.append(path)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_text(text,encoding='utf8',newline='\n')
    if stale:raise SystemExit('Stale generated files: '+', '.join(stale))
    print(json.dumps({'status':'passed','check_only':a.check,'canonical_entries':len(rows),'ranked_entries':len(ranked),'generated_files':len(outputs)},ensure_ascii=False))

if __name__=='__main__':main()
